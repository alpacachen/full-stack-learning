/**
 * 获取股票名称
 * @param stockCode 股票代码
 * @returns 股票名称
 */
export function getStockName(stockCode: string): string {
  return STOCK_NAME_MAP[stockCode] || stockCode;
}

/**
 * 随机选择一只股票
 */
