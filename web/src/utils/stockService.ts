/**
 * 股票数据服务
 * 使用新浪财经接口获取股票历史数据
 */

export interface KLineData {
  time: string; // 日期 YYYY-MM-DD
  open: number; // 开盘价
  high: number; // 最高价
  low: number; // 最低价
  close: number; // 收盘价
  volume: number; // 成交量
}

export interface StockTrainingData {
  stockCode: string; // 股票代码
  stockName: string; // 股票名称
  displayData: KLineData[]; // 展示的30天数据
  futureData: KLineData[]; // 未来5天数据（用于揭晓答案）
  allData: KLineData[]; // 完整的35天数据
}

/**
 * 从新浪财经获取股票历史数据
 * @param stockCode 股票代码 如 sh600000 或 sz000001
 * @returns K线数据数组
 */
export async function fetchStockData(stockCode: string): Promise<KLineData[]> {
  try {
    // 新浪财经历史数据接口（通过 Vite 代理访问）
    // 原始格式: https://money.finance.sina.com.cn/quotes_service/api/json_v2.php/CN_MarketData.getKLineData?symbol=sh600000&scale=240&ma=no&datalen=100
    const url = `/sina-api/quotes_service/api/json_v2.php/CN_MarketData.getKLineData?symbol=${stockCode}&scale=240&ma=no&datalen=100`;

    const response = await fetch(url);

    if (!response.ok) {
      throw new Error(`Failed to fetch stock data: ${response.statusText}`);
    }

    const data = await response.json();

    if (!data || !Array.isArray(data)) {
      throw new Error("Invalid data format from API");
    }

    // 转换数据格式
    const klineData: KLineData[] = data.map((item: any) => ({
      time: item.day, // 日期
      open: parseFloat(item.open),
      high: parseFloat(item.high),
      low: parseFloat(item.low),
      close: parseFloat(item.close),
      volume: parseFloat(item.volume),
    }));

    return klineData;
  } catch (error) {
    console.error("Error fetching stock data:", error);
    throw error;
  }
}

/**
 * 生成训练数据：从100天数据中随机选择30+5天
 * @param stockCode 股票代码
 * @returns 训练数据对象
 */
export async function generateTrainingData(
  stockCode: string
): Promise<StockTrainingData> {
  const allData = await fetchStockData(stockCode);

  if (allData.length < 35) {
    throw new Error("Not enough historical data (need at least 35 days)");
  }

  // 从100天中随机选择一个起始点，确保至少有35天的数据
  const maxStartIndex = allData.length - 35;
  const startIndex = Math.floor(Math.random() * (maxStartIndex + 1));

  // 取出连续的35天数据
  const selectedData = allData.slice(startIndex, startIndex + 35);

  // 前30天用于展示，后5天用于揭晓答案
  const displayData = selectedData.slice(0, 30);
  const futureData = selectedData.slice(30, 35);

  return {
    stockCode,
    stockName: getStockName(stockCode),
    displayData,
    futureData,
    allData: selectedData,
  };
}

